const ukPlural = new Intl.PluralRules('uk')

export const pluralRules = {
  uk: (choice: number, choicesLength: number) => {
    if (choicesLength < 3) return choice === 1 ? 0 : 1
    const category = ukPlural.select(choice)
    return category === 'one' ? 0 : category === 'few' ? 1 : 2
  },
}
